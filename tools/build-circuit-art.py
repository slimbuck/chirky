"""Export the approved native pixel grid, without resizing or palette changes.

python tools/build-circuit-art.py [--output DIRECTORY]
Requires Pillow. Alternate output supports byte-for-byte regeneration checks.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
GAME = ROOT / 'games/circuit-clash'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output', type=Path, default=GAME)
out = parser.parse_args().output
layout = json.loads((GAME / 'art/clips.json').read_text())
assert layout['cell_size'] == [96, 96] and layout['anchor'] == [48, 80]
count = sum(len(clip['names']) for clip in layout['clips'])
columns = min(layout.get('atlas_columns', 16), count)
image = Image.new('RGBA', (columns*96, ((count+columns-1)//columns)*96))
frames = []
clips = []
constants = []
for clip in layout['clips']:
    source = GAME / clip['source']
    sheet = Image.open(source).convert('RGBA')
    assert sheet.size == (len(clip['names'])*96, 96)
    assert set(sheet.getchannel('A').tobytes()) == {0, 255}
    first = len(frames)
    constants.append(f"    CC_{clip['id'].upper()}_FIRST={first}, CC_{clip['id'].upper()}_COUNT={len(clip['names'])},")
    for n, name in enumerate(clip['names']):
        cell = sheet.crop((96*n, 0, 96*(n+1), 96))
        bounds = cell.getbbox()
        assert bounds[0] > 0 and bounds[1] > 0 and bounds[2] < 96 and bounds[3] <= 80
        feet = [cell.crop((x, 0, r, 96)).getbbox()[3]-1 for x, r in [(0, 48), (48, 96)]]
        assert feet == clip['feet_rows'][n], (clip['id'], n, feet)
        image.paste(cell, ((len(frames)%columns)*96, (len(frames)//columns)*96))
        frames.append({'index': len(frames), 'clip': clip['id'], 'name': name,
                       'bounds': bounds, 'feet_rows': feet, 'timing_field': clip['timing_fields'][n]})
    clips.append({**clip, 'first': first, 'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest()})
pixels = image.tobytes()
art = out / 'assets/characters/arthur.pam'
art.parent.mkdir(parents=True, exist_ok=True)
art.write_bytes(f'P7\nWIDTH {image.width}\nHEIGHT {image.height}\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n'.encode() + pixels)
manifest = {
    'version': layout['version'], 'character': 'arthur', 'clips': clips,
    'runtime': 'assets/characters/arthur.pam', 'rgba_sha256': hashlib.sha256(pixels).hexdigest(),
    'atlas_size': list(image.size), 'atlas_columns': columns, 'cell_size': [96, 96], 'draw_size': [96, 96],
    'anchor': [48, 80], 'baseline_row': 79, 'alpha': 'binary',
    'frames': frames, 'timing': 'assets/characters/arthur.conf',
    'pending_clips': ['hit', 'knockdown'],
    'provenance': 'Native idle, body-bobbing walk, punch, airborne tuck, kick and kneeling guard. '
                  'Already reduced to the final native grid; this export copies pixels exactly.'
}
(out / 'art').mkdir(parents=True, exist_ok=True)
(out / 'art/manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
(out / 'animation_layout.h').write_text(
    '/* Generated by tools/build-circuit-art.py from art/clips.json. */\n'
    '#ifndef CIRCUIT_ANIMATION_LAYOUT_H\n#define CIRCUIT_ANIMATION_LAYOUT_H\nenum {\n' +
    '\n'.join(constants) + f'\n    CC_ATLAS_WIDTH={image.width}, CC_ATLAS_HEIGHT={image.height}, CC_ATLAS_COLUMNS={columns}, CC_CELL_SIZE=96\n}};\n#endif\n')
header = (GAME / 'tuning.h').read_text()
schema = {'version': layout['version'], 'format': 'key=value', 'unknown_fields': 'reject',
          'duplicate_fields': 'reject', 'missing_fields': 'reject', 'reload': 'restart game',
          'tick_rate_note': 'Game updates; nominal 60 Hz. Native currently follows presentation.',
          'fp8_note': '1 = 1/8 framebuffer pixel; velocity per update, acceleration per update squared.'}
for kind in ['CHARACTER', 'STAGE']:
    block = header.split(f'#define CC_{kind}_FIELDS(X)', 1)[1].split('\n#define', 1)[0]
    fields = [{'key': name, 'type': 'integer', 'minimum': int(lo), 'maximum': int(hi), 'required': True}
              for name, lo, hi in re.findall(r'X\((\w+),(\d+),(\d+)\)', block)]
    fields.append({'key': 'name', 'type': 'string', 'minLength': 1, 'maxLength': 23, 'required': True})
    if kind == 'CHARACTER':
        fields.append({'key': 'atlas', 'type': 'asset-path', 'required': True, 'cellSize': [96, 96], 'frameCount': count})
    schema[kind.lower()] = fields
schema['constraints'] = ['crouching_height_px <= standing_height_px'] + [
    f'{prefix}_bottom_px < {prefix}_top_px' for prefix in ['punch','kick','crouch_punch','crouch_kick','air_punch','air_kick']]
schema['constraints'] += [f'{prefix}_followthrough_ticks < {prefix}_recovery_ticks'
                          for prefix in ['punch','kick','crouch_punch','crouch_kick','air_punch','air_kick']]
schema['moves'] = [{'id': prefix, 'label': label} for prefix,label in [
    ('punch','Standing punch'),('kick','Standing kick'),('crouch_punch','Crouching punch'),
    ('crouch_kick','Crouching kick'),('air_punch','Air punch'),('air_kick','Air kick')]]
(out / 'content-schema.json').write_text(json.dumps(schema, indent=2)+'\n')
print(f'Exported native {image.width}x{image.height} atlas, animation layout, art manifest and tuning schema.')
